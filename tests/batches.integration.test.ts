interface LocalBatchHarness {
  batchManager: BatchManager
  downloadManager: DownloadManager
  service: Aria2Service
  database: DownloadDatabase
  downloadDir: string
  root: string
}

async function createHarness(): Promise<LocalBatchHarness> {
  await fs.mkdir(TEMP_BASE, { recursive: true })
  const root = await fs.mkdtemp(path.join(TEMP_BASE, 'batch-integration-'))
  const downloadDir = path.join(root, 'downloads')
  const database = openDownloadDatabase(
    path.join(root, 'downloads.sqlite3')
  )
  const service = new Aria2Service(() => downloadDir)
  await service.start()

  const downloadManager = new DownloadManager(
    service,
    downloadDir,
    () => undefined,
    database
  )
  const batchManager = new BatchManager({
    downloads: downloadManager,
    mediaJobs: createMediaStub(),
    collectionEngine: createCollectionStub(),
    pixeldrain: createPixeldrainAdapter(),
    database,
    onUpdate: () => undefined,
    pollIntervalMs: 100,
    progressPersistIntervalMs: 100,
    openExternal: () => undefined
  })

  return {
    batchManager,
    downloadManager,
    service,
    database,
    downloadDir,
    root
  }
}

async function tearDownHarness(
  harness: LocalBatchHarness | null,
  removeRoot = true
): Promise<void> {
  if (!harness) return
  try {
    harness.batchManager.close()
  } catch {
    // Best effort during teardown.
  }
  try {
    harness.downloadManager.close()
  } catch {
    // Best effort during teardown.
  }
  try {
    await harness.service.stop()
  } catch {
    // Best effort during teardown.
  }
  if (removeRoot) {
    await removeDirectory(harness.root)
  }
}

async function removeDirectory(dir: string): Promise<void> {
  for (let attempt = 0; attempt < 10; attempt += 1) {
    try {
      await fs.rm(dir, { recursive: true, force: true })
      return
    } catch {
      if (attempt === 9) return
      await delay(200)
    }
  }
}

function getDownload(
  manager: DownloadManager,
  id: string
): DownloadItem | null {
  return (
    manager.getSnapshot().downloads.find((record) => record.id === id) ?? null
  )
}

function getItem(batch: Batch, itemId: string): BatchItem {
  const item = batch.items.find((candidate) => candidate.id === itemId)
  if (!item) throw new Error(`Batch item ${itemId} is missing.`)
  return item
}

async function waitForBatch(
  manager: BatchManager,
  batchId: string,
  predicate: (batch: Batch) => boolean,
  label: string,
  timeoutMs = 90_000
): Promise<Batch> {
  const deadline = Date.now() + timeoutMs
  let last: Batch | null = null

  while (Date.now() < deadline) {
    manager.refresh()
    last = manager.getBatch(batchId)
    if (predicate(last)) return last
    await delay(100)
  }

  throw new Error(
    `Timed out waiting for ${label}. Last batch state: ${JSON.stringify(last)}`
  )
}

async function waitForDownloadStatus(
  manager: DownloadManager,
  id: string,
  predicate: (download: DownloadItem) => boolean,
  label: string,
  timeoutMs = 30_000
): Promise<DownloadItem> {
  const deadline = Date.now() + timeoutMs
  let last: DownloadItem | null = null

  while (Date.now() < deadline) {
    last = getDownload(manager, id)
    if (last && predicate(last)) return last
    await delay(100)
  }

  throw new Error(
    `Timed out waiting for ${label}. Last download state: ${JSON.stringify(last)}`
  )
}

interface ReopenedHarness {
  manager: BatchManager
  downloads: DownloadManager
  database: DownloadDatabase
}

/** Reopen the same SQLite file with a fresh manager and no running aria2. */
function reopenBatchManager(databasePath: string, root: string): ReopenedHarness {
  const database = openDownloadDatabase(databasePath)
  const service = new Aria2Service(() => path.join(root, 'downloads-reopened'))
  const downloads = new DownloadManager(
    service,
    path.join(root, 'downloads-reopened'),
    () => undefined,
    database
  )
  const manager = new BatchManager({
    downloads,
    mediaJobs: createMediaStub(),
    collectionEngine: createCollectionStub(),
    pixeldrain: createPixeldrainAdapter(),
    database,
    onUpdate: () => undefined,
    pollIntervalMs: 0,
    openExternal: () => undefined
  })
  return { manager, downloads, database }
}

