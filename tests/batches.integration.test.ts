const TEMP_BASE = path.join(os.tmpdir(), 'opencode')
const DIRECT_PAYLOAD_SIZE = 512 * 1024
const THROTTLED_PAYLOAD_SIZE = 8 * 1024 * 1024
const THROTTLE_CHUNK_SIZE = 32 * 1024
const THROTTLE_CHUNK_DELAY_MS = 40

function delay(ms: number): Promise<void> {
  return new Promise((resolve) => setTimeout(resolve, ms))
}

/** Deterministic, non-repeating bytes make an exact comparison meaningful. */
function buildPayload(size: number, seed: number): Buffer {
  const payload = Buffer.allocUnsafe(size)
  for (let index = 0; index < size; index += 1) {
    payload[index] = (index * 31 + seed) & 0xff
  }
  return payload
}

interface RangeRequestRecord {
  start: number
  end: number
}

interface TestHttpServer {
  url: (filename: string) => string
  close: () => Promise<void>
}

function parseRangeHeader(
  header: string | undefined,
  totalLength: number
): RangeRequestRecord | null | 'invalid' {
  if (!header) return null

  const match = /^bytes=(\d*)-(\d*)$/.exec(header.trim())
  if (!match) return 'invalid'

  const rawStart = match[1] ?? ''
  const rawEnd = match[2] ?? ''
  if (rawStart === '' && rawEnd === '') return 'invalid'

  let start: number
  let end: number
  if (rawStart === '') {
    const suffixLength = Number(rawEnd)
    if (!Number.isSafeInteger(suffixLength) || suffixLength <= 0) return 'invalid'
    start = Math.max(0, totalLength - suffixLength)
    end = totalLength - 1
  } else {
    start = Number(rawStart)
    end = rawEnd === '' ? totalLength - 1 : Number(rawEnd)
  }

  if (
    !Number.isSafeInteger(start) ||
    !Number.isSafeInteger(end) ||
    start < 0 ||
    end < start ||
    start >= totalLength
  ) {
    return 'invalid'
  }

  return { start, end: Math.min(end, totalLength - 1) }
}

function waitForDrain(response: ServerResponse): Promise<void> {
  return new Promise((resolve) => {
    const finish = (): void => {
      response.removeListener('drain', finish)
      response.removeListener('close', finish)
      response.removeListener('error', finish)
      resolve()
    }
    response.once('drain', finish)
    response.once('close', finish)
    response.once('error', finish)
  })
}

/** Write slowly enough that a pause reliably lands before completion. */
async function writeThrottled(
  response: ServerResponse,
  body: Buffer
): Promise<void> {
  for (let offset = 0; offset < body.length; offset += THROTTLE_CHUNK_SIZE) {
    if (response.destroyed || response.writableEnded) return

    const chunk = body.subarray(
      offset,
      Math.min(offset + THROTTLE_CHUNK_SIZE, body.length)
    )
    if (!response.write(chunk)) {
      await waitForDrain(response)
    }
    if (offset + THROTTLE_CHUNK_SIZE < body.length) {
      await delay(THROTTLE_CHUNK_DELAY_MS)
    }
  }

  if (!response.destroyed && !response.writableEnded) {
    response.end()
  }
}

function serveBuffer(
  request: IncomingMessage,
  response: ServerResponse,
  body: Buffer,
  filename: string,
  throttle: boolean,
  range: RangeRequestRecord | null
): void {
  const start = range?.start ?? 0
  const end = range?.end ?? body.length - 1
  const headers: Record<string, string | number> = {
    'content-type': 'application/octet-stream',
    'content-length': end - start + 1,
    'accept-ranges': 'bytes',
    'content-disposition': `attachment; filename="${filename}"`
  }
  if (range) {
    headers['content-range'] = `bytes ${start}-${end}/${body.length}`
  }

  response.writeHead(range ? 206 : 200, headers)
  if (request.method === 'HEAD') {
    response.end()
    return
  }

  const slice = body.subarray(start, end + 1)
  if (!throttle) {
    response.end(slice)
    return
  }

  void writeThrottled(response, slice).catch(() => {
    if (!response.destroyed) response.destroy()
  })
}

function startHttpServer(
  directPayload: Buffer,
  throttledPayload: Buffer
): Promise<TestHttpServer> {
  const sockets = new Set<Socket>()

  const server = createHttpServer((request, response) => {
    // Client disconnects during pause are normal; never surface them as
    // unhandled response errors.
    response.on('error', () => undefined)

    const pathname = new URL(
      request.url ?? '/',
      'http://127.0.0.1'
    ).pathname

    if (pathname === '/batch-complete.bin') {
      const range = parseRangeHeader(
        request.headers.range,
        directPayload.length
      )
      if (range === 'invalid') {
        response.writeHead(416, {
          'content-range': `bytes */${directPayload.length}`
        })
        response.end()
        return
      }
      serveBuffer(
        request,
        response,
        directPayload,
        'batch-complete.bin',
        false,
        range
      )
      return
    }

    if (pathname === '/batch-throttled.bin') {
      const range = parseRangeHeader(
        request.headers.range,
        throttledPayload.length
      )
      if (range === 'invalid') {
        response.writeHead(416, {
          'content-range': `bytes */${throttledPayload.length}`
        })
        response.end()
        return
      }
      serveBuffer(
        request,
        response,
        throttledPayload,
        'batch-throttled.bin',
        true,
        range
      )
      return
    }

    response.writeHead(404, { 'content-type': 'text/plain' })
    response.end('Not found')
  })

  server.on('connection', (socket) => {
    sockets.add(socket)
    socket.once('close', () => sockets.delete(socket))
  })

  return new Promise((resolve, reject) => {
    server.once('error', reject)
    server.listen(0, '127.0.0.1', () => {
      const address = server.address()
      if (typeof address !== 'object' || address === null) {
        reject(new Error('HTTP test server did not start.'))
        return
      }

      resolve({
        url: (filename: string) =>
          `http://127.0.0.1:${address.port}/${filename}`,
        close: async () => {
          for (const socket of sockets) socket.destroy()
          sockets.clear()
          server.closeAllConnections?.()
          await new Promise<void>((done) => {
            server.close(() => done())
          })
        }
      })
    })
  })
}

