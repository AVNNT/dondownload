/**
 * One-job Netscape cookie files for yt-dlp.
 *
 * The browser extension reads cookies only after an explicit per-origin
 * opt-in and sends a single flattened Cookie header for one operation. The
 * desktop app never persists that header: it is converted to a short-lived
 * Netscape file, passed to exactly one yt-dlp child, and removed as soon as
 * that child settles. No error, log or database row includes cookie text.
 */

export const COOKIE_FILE_PREFIX = '.dondownload-cookies-'

const COOKIE_NAME = /^[!#$%&'*+\-.^_`|~0-9A-Za-z]+$/
const MAX_COOKIE_PAIRS = 200
const MAX_COOKIE_LINE_LENGTH = 4096
const MULTI_PART_SUFFIXES = new Set([
  'co.uk',
  'co.jp',
  'co.nz',
  'co.za',
  'com.au',
  'com.br',
  'com.mx',
  'com.sg',
  'com.tr',
  'com.tw',
  'com.hk'
])

/**
 * Domain scope for the generated file. The extension sends a header, not
 * per-cookie domains, so use the public-ish site domain and include
 * subdomains; a Vimeo page's cookies then also reach player.vimeo.com.
 */
export function cookieFileDomain(hostname: string): string {
  const host = hostname.trim().toLowerCase().replace(/\.$/, '')
  if (host.length === 0 || /^\[|\]$/.test(host)) return host
  // Never shorten an IPv4 literal to its last two labels.
  if (/^\d{1,3}(?:\.\d{1,3}){3}$/.test(host)) return host
  const labels = host.split('.').filter((label) => label.length > 0)
  if (labels.length <= 2) return host
  const lastTwo = labels.slice(-2).join('.')
  if (MULTI_PART_SUFFIXES.has(lastTwo)) {
    return labels.slice(-3).join('.')
  }
  return lastTwo
}

interface CookiePair {
  name: string
  value: string
}

function parseCookieHeader(header: string): CookiePair[] {
  const pairs: CookiePair[] = []
  for (const part of header.split(';')) {
    const trimmed = part.trim()
    if (trimmed.length === 0) continue
    const separator = trimmed.indexOf('=')
    if (separator <= 0) continue
    const name = trimmed.slice(0, separator).trim()
    const value = trimmed.slice(separator + 1).trim()
    if (
      !COOKIE_NAME.test(name) ||
      value.length > MAX_COOKIE_LINE_LENGTH ||
      // eslint-disable-next-line no-control-regex -- rejecting control characters is the security intent here
      /[\t\r\n\u0000]/.test(name) ||
      // eslint-disable-next-line no-control-regex -- rejecting control characters is the security intent here
      /[\t\r\n\u0000]/.test(value)
    ) {
      continue
    }
    pairs.push({ name, value })
    if (pairs.length >= MAX_COOKIE_PAIRS) break
  }
  return pairs
}

/**
 * Build a Netscape cookies.txt body accepted by yt-dlp/curl. Invalid pairs are
 * skipped rather than forwarded as another header or a malformed line.
 */
export function buildNetscapeCookieFile(
  cookieHeader: string,
  hostname: string
): string {
  const domain = cookieFileDomain(hostname)
  if (domain.length === 0) {
    throw new Error('A cookie host is required.')
  }
  const lines = [
    '# Netscape HTTP Cookie File',
    '# Generated by DonDownload for one yt-dlp operation. Do not edit.'
  ]
  for (const pair of parseCookieHeader(cookieHeader)) {
    lines.push(
      `.${domain}\tTRUE\t/\tTRUE\t0\t${pair.name}\t${pair.value}`
    )
  }
  return `${lines.join('\n')}\n`
}
